const LANG_KEY = 'zupix_user_language';

export function getSavedLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && saved in TRANSLATIONS) {
      return saved as LanguageCode;
    }
  } catch (e) {
    console.warn(e);
  }
  return 'en-GB';
}

export function setSavedLanguage(lang: LanguageCode): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (e) {
    console.warn(e);
  }
}

export function t(key: string, lang: LanguageCode = 'en-GB'): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS['en-GB'];
  return dictionary[key] || TRANSLATIONS['en-GB'][key] || key;
}
